def group_defaults() -> Dict[Tuple[str, str], str]:
    result = {item.pair: item.default for item in FIELDS}
    result.update(UNSUPPORTED)
    return result


def iter_groups() -> Iterable[Tuple[str, str]]:
    yield from FIELD_BY_PAIR
    yield from UNSUPPORTED


